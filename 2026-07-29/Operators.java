
class Operators {
    public static void main(String[] args) {
        int a = 5;
        double b = 5;
        char c = 'L';
        String name = "LIKITH";
        System.out.println("The Arithmetic Operators:");
        System.out.println("The addition: " + (a + b));
        System.out.println("The String: " + (c + name));
        System.out.println("THE INT MULTIPLICATION: " + (a * b));
        System.out.println("THE DOUBLE DIVISION: " + (a / b));
        System.out.println("THE INT MODULO: " + (a % b));
    }
}
